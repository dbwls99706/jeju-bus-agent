const assert=require('node:assert/strict');
const {summarize,parseRecords,MAX_BYTES}=require('../static/local-csv.js');
const h='base_date,day_of_week,base_hour,user_type,user_count\n';
const row='20240101,월,01시-06시,일반,10';
let s=summarize('\ufeff'+h+row+'\r\n20240102,화,07시-09시,"일반, 기타",20\r\n');
assert.equal(s.rows,2);assert.equal(s.total,30);assert.equal(s.minDate,'2024-01-01');assert.equal(s.maxDate,'2024-01-02');assert.equal(s.byWeekday['월'],10);assert.equal(s.byHour['07시-09시'],20);assert.equal(s.hourRows['10시-12시'],0);assert.equal(s.weekdayRows['월'],1);
assert.deepEqual(parseRecords('"a""b",c\n'),[['a"b','c']]);
assert.throws(()=>summarize(h+row+'\n'+row),/중복/);
assert.throws(()=>summarize(h+row.replace(',월,',',화,')),/요일/);
assert.throws(()=>summarize(h+row.replace('20240101','20240230')),/날짜/);
assert.throws(()=>summarize(h+row.replace(',10',',-1')),/정수/);
assert.throws(()=>summarize(h),/데이터 행/);
assert.throws(()=>summarize(h+row+',oops'),/5개/);
assert.throws(()=>parseRecords('"open'),/닫히지/);
assert.throws(()=>parseRecords('"closed"extra'),/구분자/);
assert.throws(()=>parseRecords('x'.repeat(MAX_BYTES+1)),/5MB/);
assert.throws(()=>summarize(h+row.replace(',10',',9007199254740992')),/정수/);
s=summarize(h+row.replace('일반','<script>alert(1)</script>'));assert.equal(s.types[0],'<script>alert(1)</script>');
assert.equal(summarize('user_count,user_type,base_hour,day_of_week,base_date\n10,일반,01시-06시,월,20240101').total,10);
assert.throws(()=>parseRecords('a,b,c,d,e\n'+'1,2,3,4,5\n'.repeat(100001)),/100,000/);
const fs=require('node:fs');const code=fs.readFileSync(require.resolve('../static/local-csv.js'),'utf8');assert(!/\b(fetch|XMLHttpRequest|WebSocket|sendBeacon|localStorage|sessionStorage)\s*[.(]/.test(code));assert(!code.includes('innerHTML'));
console.log('PASS: local CSV parser, validation, aggregation, safe rendering and no network/storage calls');
